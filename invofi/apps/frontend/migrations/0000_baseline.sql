-- ── Supabase compatibility shim ──────────────────────────────────────────────
-- Only created when absent; on Supabase the real auth schema takes precedence.

create schema if not exists auth;

create table if not exists auth.users (
  id         uuid primary key,
  email      text unique,
  created_at timestamptz not null default now()
);

-- (distinct dollar-quote tags: the function body's $uid$ is nested inside
-- the do-block's $shim$ — plain $$ would terminate the outer block)
do $shim$ begin
  if not exists (
    select 1 from pg_proc
    where proname = 'uid' and pronamespace = 'auth'::regnamespace
  ) then
    create function auth.uid() returns uuid language sql stable as $uid$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $uid$;
  end if;
end $shim$;

