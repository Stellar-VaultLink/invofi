-- Co-signer notification (ADR-0006 §5): emits a NOTIFY an Edge Function or
-- worker can LISTEN on; harmless when nothing is listening.
create or replace function notify_pending_transaction()
returns trigger language plpgsql as $$
begin
  perform pg_notify(
    'pending_transaction_created',
    json_build_object(
      'id', new.id,
      'title', new.title,
      'initiator', new.initiator,
      'amount', new.amount,
      'currency', new.currency,
      'required_signatures', new.required_signatures,
      'expires_at', new.expires_at
    )::text
  );
  return new;
end;
$$;

drop trigger if exists pending_transactions_notify on pending_transactions;
