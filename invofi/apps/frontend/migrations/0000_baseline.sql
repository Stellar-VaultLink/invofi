-- Supabase-specific privilege handling: RLS is enabled with no client policies
-- (anon/authenticated denied) and only the service role writes. On vanilla
-- Postgres these roles don't exist — guard so the file runs unchanged.
do $$ begin
  revoke all on table sep10_used_challenges from anon, authenticated;
exception when undefined_object then null; end $$;

do $$ begin
  grant insert on table sep10_used_challenges to service_role;
exception when undefined_object then null; end $$;

-- Portable retention helper (replaces the Supabase pg_cron schedule; call from
-- the keeper/GitHub Action on Neon — rows past the 10-minute challenge window
-- serve no replay-protection purpose).
create or replace function purge_expired_sep10_challenges()
returns integer language plpgsql as $$
declare deleted_count integer;
begin
  delete from sep10_used_challenges
  where created_at < now() - interval '1 hour';
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

